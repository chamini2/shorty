import AppKit
import XCTest
@testable import ShortyCore

final class ClipboardPrivacyTests: XCTestCase {
    private var board: NSPasteboard!

    override func setUp() {
        super.setUp()
        board = NSPasteboard(name: NSPasteboard.Name("dev.shorty.tests.\(UUID().uuidString)"))
    }

    override func tearDown() {
        board.releaseGlobally()
        board = nil
        super.tearDown()
    }

    private func concealed(_ type: String, text: String = "hunter2") {
        let marker = NSPasteboard.PasteboardType(type)
        board.clearContents()
        board.declareTypes([.string, marker], owner: nil)
        board.setString(text, forType: .string)
        board.setData(Data(), forType: marker)
    }

    func testASecretIsNeverRead() {
        concealed("org.nspasteboard.ConcealedType")

        XCTAssertNil(ClipboardItem.read(from: board))
    }

    func testTheOtherDoNotKeepMarkersAreHonoured() {
        for type in ["org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"] {
            concealed(type, text: "temporary")

            XCTAssertNil(ClipboardItem.read(from: board), "\(type) should not be kept")
        }
    }

    func testAnOrdinaryCopyIsStillRead() throws {
        board.clearContents()
        board.declareTypes([.string], owner: nil)
        board.setString("ordinary text", forType: .string)

        let item = try XCTUnwrap(ClipboardItem.read(from: board))

        XCTAssertEqual(item.plainText, "ordinary text")
    }

    func testPrivateTypesAreRecognisedAmongOthers() {
        XCTAssertFalse(ClipboardItem.isPrivate(types: ["public.utf8-plain-text", "public.html"]))
        XCTAssertTrue(
            ClipboardItem.isPrivate(types: ["public.utf8-plain-text", "org.nspasteboard.ConcealedType"])
        )
    }
}
